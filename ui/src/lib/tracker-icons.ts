// The tracker icon set.
//
// A second, deliberately different family from `icons.ts`. Those are the
// application's chrome -- 1.5px line icons in the Lucide idiom, drawn to sit
// quietly beside text. These are the opposite job: a tracker's icon is the
// thing you aim at with the mouse twice a day, twenty of them share a row,
// and it has to be identifiable at 18px in the corner of a chip. Line icons
// lose that fight. Solid ones win it.
//
// House rules, so additions stay consistent:
//   - 24x24 viewBox, artwork inside a 20x20 live area.
//   - Filled shapes only. No strokes anywhere: the chip supplies a tinted
//     tile and the glyph is a single mass of `currentColor` on top of it.
//   - Detail is cut *out* of the mass with `fill-rule="evenodd"` rather than
//     drawn on top of it, so an icon stays one colour and reads on any tint.
//   - Nothing thinner than about 1.4 units, or it disappears at 16px. That
//     rules out most of what a line icon can say, which is why the shapes
//     here are simpler than their line equivalents rather than smaller.
//   - Corners rounded generously. These are friendly things to press.
//
// Original artwork, drawn for this application. The full-circle hole idiom
// (`a1.6 1.6 0 1 0 0 3.2 1.6 1.6 0 0 0 0-3.2Z`) is the one convention
// borrowed from the wider SVG world, because it is simply how a filled icon
// punches a round hole.

