// Compare the Rust record types against the hand-written mirror in
// `ui/src/lib/types.ts`.
//
// `types.ts` says at its own top that it mirrors serde's representation of
// the record structs in `everyday-core` and is deliberately hand-written --
// nothing regenerates it, so nothing previously caught a field renamed in
// Rust and forgotten here, or the reverse. This script is that check. It
// does not replace `types.ts` or write to it; see
// `docs/plans/architecture-refactor.md`, Phase 5.
//
// The Rust side of the comparison is
// `crates/everyday-core/schema/record-schema.json`, a JSON Schema for the
// record types (the ones with their own id and table or sealed payload --
// not every value type embedded inside one) generated by `schemars` behind
// the `schema` feature, which is off by default and so not part of the
// shipped binary. It is committed, so this check runs without a Rust build.
// To regenerate it after a Rust change:
//
//   CARGO_TARGET_DIR=... UPDATE_SCHEMA=1 \
//     cargo test -p everyday-core --features schema --test schema
//
// This script then reads that file and `types.ts` itself (parsed with the
// TypeScript compiler API, not `require`d -- it is not valid JS) and
// compares, per type: which field names exist on each side, and whether a
// field is optional on each side (Rust: absent from the schema's
// `required`, which `schemars` derives from `Option<T>`, `#[serde(default)]`
// and `skip_serializing_if`; TypeScript: `?:` or a `| null` union).
//
// Every difference that exists today is recorded, with a reason, in
// `ui/scripts/types-drift-allowlist.json`. A difference not in that file
// fails the check; an allowlist entry that stops reproducing a real
// difference also fails it, so the file stays a true record of how far the
// two sides are apart rather than growing forever.
//
//   node ui/scripts/check-types-drift.mjs

import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..', '..')

const schemaPath = join(root, 'crates', 'everyday-core', 'schema', 'record-schema.json')
const allowlistPath = join(here, 'types-drift-allowlist.json')
const typesPath = join(here, '..', 'src', 'lib', 'types.ts')

const schema = JSON.parse(readFileSync(schemaPath, 'utf8'))
const allowlist = JSON.parse(readFileSync(allowlistPath, 'utf8'))
const typesSource = readFileSync(typesPath, 'utf8')

// ── Read the TypeScript side ──────────────────────────────────────────────

const sourceFile = ts.createSourceFile(
  'types.ts',
  typesSource,
  ts.ScriptTarget.Latest,
  /* setParentNodes */ true,
)

/** Whether `type` is a union that admits `null`, the shape `Option<T>` takes
 * when it is not also behind `?:`. */
function admitsNull(type) {
  if (!type || !ts.isUnionTypeNode(type)) return false
  return type.types.some(
    (t) => ts.isLiteralTypeNode(t) && t.literal.kind === ts.SyntaxKind.NullKeyword,
  )
}

/** `interface name`'s own members, keyed by field name -> `{ optional }`.
 * Only top-level `export interface` declarations are read: every record
 * type in the schema is one, and reading only these -- not `type` aliases,
 * not members inherited through `extends` -- keeps a false match out of
 * reach if a name ever collides with an unrelated view type. */
const tsInterfaces = new Map()
for (const node of sourceFile.statements) {
  if (!ts.isInterfaceDeclaration(node)) continue
  const fields = new Map()
  for (const member of node.members) {
    if (!ts.isPropertySignature(member)) continue
    const name = member.name.getText(sourceFile)
    const optional = Boolean(member.questionToken) || admitsNull(member.type)
    fields.set(name, { optional })
  }
  tsInterfaces.set(node.name.text, fields)
}

// ── Compare ────────────────────────────────────────────────────────────────

/** One difference: `type` is a schema key, `field` is `null` for "the type
 * itself has no counterpart". */
function key(f) {
  return f.field ? `${f.type}.${f.field}: ${f.kind}` : `${f.type}: ${f.kind}`
}

const findings = []
let fieldsChecked = 0

for (const [typeName, rustSchema] of Object.entries(schema)) {
  const tsFields = tsInterfaces.get(typeName)
  if (!tsFields) {
    findings.push({ type: typeName, field: null, kind: 'missing-in-ts' })
    continue
  }

  const rustProps = rustSchema.properties ?? {}
  const rustRequired = new Set(rustSchema.required ?? [])
  const rustFieldNames = new Set(Object.keys(rustProps))

  for (const field of rustFieldNames) {
    fieldsChecked++
    if (!tsFields.has(field)) {
      findings.push({ type: typeName, field, kind: 'field-only-in-rust' })
      continue
    }
    const rustOptional = !rustRequired.has(field)
    const tsOptional = tsFields.get(field).optional
    if (rustOptional !== tsOptional) {
      findings.push({ type: typeName, field, kind: 'optionality' })
    }
  }
  for (const field of tsFields.keys()) {
    if (!rustFieldNames.has(field)) {
      findings.push({ type: typeName, field, kind: 'field-only-in-ts' })
    }
  }
}

const allowed = new Map(allowlist.map((e) => [key(e), e.reason]))
const unexpected = findings.filter((f) => !allowed.has(key(f)))
const stale = allowlist.filter((e) => !findings.some((f) => key(f) === key(e)))

if (unexpected.length > 0) {
  console.error(
    `check-types-drift: ${unexpected.length} difference(s) between the Rust record types and ` +
      `types.ts that are not in the allowlist:\n`,
  )
  for (const f of unexpected) console.error(`  ${key(f)}`)
  console.error(
    `\nEach is either a real bug worth fixing in types.ts (or the Rust struct, if that is the ` +
      `one that drifted), or an intentional difference that belongs in ` +
      `ui/scripts/types-drift-allowlist.json with a one-line reason.`,
  )
  process.exit(1)
}

if (stale.length > 0) {
  console.error(
    `check-types-drift: ${stale.length} allowlist entr${stale.length === 1 ? 'y' : 'ies'} no ` +
      `longer reproduce(s) a real difference -- types.ts and the Rust agree now, so remove ` +
      `the entry:\n`,
  )
  for (const e of stale) console.error(`  ${key(e)}`)
  process.exit(1)
}

console.log(
  `check-types-drift: ${Object.keys(schema).length} record types, ${fieldsChecked} fields ` +
    `checked against types.ts (${allowlist.length} allowlisted difference` +
    `${allowlist.length === 1 ? '' : 's'}).`,
)
