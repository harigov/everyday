#!/usr/bin/env node
// Bundle FiveFilters' site rules (https://github.com/fivefilters/ftr-site-config,
// released to the public domain) into the one file the Feed reads them from:
// `crates/jatayu-service/src/news/site_rules.txt`. See `news/rules.rs` for
// what the rules do and which of them are read.
//
//   node scripts/site-rules.mjs [<ftr-site-config checkout>]
//
// With no checkout, the repository's default branch is cloned into a new
// temporary directory and removed afterwards. Either way the bundle names the
// commit it came from, so a refresh is a reviewable diff.
//
// Only the directives `rules.rs` reads are kept, in the order each site's
// file gives them: the rest -- titles and dates (a feed has its own), the
// pages of multi-page articles and logins (which would mean fetching more),
// test addresses and comments -- would only make the file bigger.

import { execFileSync } from 'node:child_process'
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const KEPT = new Set([
  'body',
  'strip',
  'strip_id_or_class',
  'strip_image_src',
  'author',
  'find_string',
  'replace_string',
])

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'crates/jatayu-service/src/news/site_rules.txt')

let checkout = process.argv[2]
let scratch = null
if (!checkout) {
  scratch = mkdtempSync(join(tmpdir(), 'ftr-site-config-'))
  checkout = join(scratch, 'checkout')
  execFileSync('git', [
    'clone',
    '--quiet',
    '--depth',
    '1',
    'https://github.com/fivefilters/ftr-site-config.git',
    checkout,
  ])
}

try {
  const commit = execFileSync('git', ['-C', checkout, 'log', '-1', '--format=%H %cs'])
    .toString()
    .trim()
  const files = readdirSync(checkout)
    .filter((name) => name.endsWith('.txt') && name !== 'LICENSE.txt')
    .sort()

  const sections = []
  let directives = 0
  for (const name of files) {
    const lines = []
    for (const raw of readFileSync(join(checkout, name), 'utf8').split(/\r?\n/)) {
      const line = raw.trim()
      if (!line || line.startsWith('#')) continue
      // `replace_string(<find>): <replace>` is its own directive's short form.
      const directive = /^([a-z_]+)(?:\(|\s*:)/.exec(line)?.[1]
      if (!directive || !KEPT.has(directive)) continue
      lines.push(line)
    }
    if (lines.length === 0) continue
    directives += lines.length
    sections.push(`== ${name.slice(0, -'.txt'.length).toLowerCase()}\n${lines.join('\n')}`)
  }

  const header = [
    "# FiveFilters' site rules for extracting articles, from",
    `# https://github.com/fivefilters/ftr-site-config at ${commit}.`,
    '# Released to the public domain (CC0). Generated by scripts/site-rules.mjs --',
    '# do not edit by hand; see crates/jatayu-service/src/news/rules.rs.',
    `# ${sections.length} sites, ${directives} directives.`,
  ].join('\n')
  writeFileSync(out, `${header}\n\n${sections.join('\n\n')}\n`)
  console.log(`${out}: ${sections.length} sites, ${directives} directives, from ${commit}`)
} finally {
  if (scratch) rmSync(scratch, { recursive: true, force: true })
}
