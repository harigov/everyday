//! Tauri's build step, with the application's own commands declared to it.
//!
//! # Why the commands are listed here
//!
//! Tauri keeps an access-control list for what a page may ask the shell to do
//! -- the files in `capabilities/` -- but it only applies that list to a
//! command the build knows about. A bare `tauri_build::build()` knows about
//! none of the application's own commands, and an application that declares
//! none gets no check on them at all: every window, however narrow its
//! capability file reads, could call every `#[tauri::command]` registered in
//! `src/lib.rs`'s `invoke_handler`. The small windows that work over other
//! applications (writing help's popup, voice typing's pill, the meeting card)
//! could have started a server or opened a vault.
//!
//! Declaring the commands here makes Tauri generate an `allow-<command>` and a
//! `deny-<command>` permission for each (the command's name with its
//! underscores turned into hyphens: `mcp_issue_token` is `allow-mcp-issue-token`),
//! and from then on a command that no capability grants to a window is refused
//! for that window. The permissions are written to `permissions/autogenerated/`
//! on every build; that directory is not committed.
//!
//! # Adding a command
//!
//! 1. Register it in `invoke_handler` in `src/lib.rs`, as before.
//! 2. Add its name to [`APP_COMMANDS`] below.
//! 3. Grant `allow-<name>` to every window whose page calls it: always to
//!    `capabilities/default.json` (the main window and the app windows get
//!    every command), and to the narrow windows' files
//!    (`capabilities/writing.json`, `voice-typing.json`, `recording.json`) only
//!    if their own page calls it. A command nobody grants is refused for
//!    everyone, which shows up as "Command ... not allowed by ACL" in the
//!    window's console and nowhere else.
//!
//! A mistake in step 2 or 3 is caught by `cargo test -p karmayoga-app --lib
//! acl::`, which compares this list with `invoke_handler` and with the
//! capability files, so a forgotten command fails a test and not somebody's
//! click. A typo in a permission name fails this build.
//!
//! A service command -- anything reached through `call`, which is most of what
//! the interface does -- is not listed here: `call` is one Tauri command, and
//! the per-window check on *which* service commands a narrow window may reach
//! through it is in `src/guard.rs`.

