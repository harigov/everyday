fn main() {
    // `tauri_build::build()` does this itself with default attributes: print
    // the error where the build log shows it, then fail, rather than panic with
    // a backtrace that says nothing more.
    if let Err(error) = tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(APP_COMMANDS)),
    ) {
        println!("{error:#}");
        std::process::exit(1);
    }
}
